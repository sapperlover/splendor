"""Compare this human game's clustered tier-three blinds to model9 self-play."""
from collections import Counter
import hashlib
import json
from pathlib import Path

import numpy as np

ROOT=Path(__file__).resolve().parents[2]
ART=Path(__file__).resolve().parent
report=json.loads((ART/'summary.json').read_text())
source=next(r for r in report['rows'] if r['source_model_online_round']==9)
folder=ROOT/source['path']
stream=hashlib.sha256()
players=Counter();games=Counter();checks=Counter();joint=Counter()
for game_id,path in enumerate(sorted((folder/'games').glob('game-*.npz'))):
    assert path.name==f'game-{game_id:06d}.npz'
    with np.load(path,allow_pickle=False) as archive:
        raw=archive['metadata_json'].tobytes()
        meta=json.loads(raw)
    stream.update(path.name.encode()+b'\0'+raw+b'\0')
    total=[0,0];tier3=[0,0]
    for row in meta['trace']['actions']:
        if row['action']['__type__']=='ReserveDeck':
            p=row['player_id'];total[p]+=1
            tier3[p]+=int(row['action']['tier']==3)
    for n,t in zip(total,tier3,strict=True):
        players[str(t)]+=1
        joint[f'{n},{t}']+=1
        checks['players_all_blinds_ge3']+=int(n>=3)
        checks['players_tier3_blinds_ge3']+=int(t>=3)
        checks['players_exactly3_blinds_all_tier3']+=int(n==t==3)
    games[str(sum(tier3))]+=1
    checks['games_blinds_ge4']+=int(sum(total)>=4)
    checks['games_tier3_blinds_ge4']+=int(sum(tier3)>=4)
    checks['games_exactly4_blinds_all_tier3']+=int(sum(total)==sum(tier3)==4)
assert stream.hexdigest()==source['metadata_stream_sha256']
assert sum(int(k)*v for k,v in players.items())==source['stats']['tiers']['3']
assert sum(players.values())==20000 and sum(games.values())==10000
out=dict(scope='All 10000 self-play games generated by the exact local human-play model (online9). '
         'Both seats counted: 20000 player-games. Self-play noise/budgets differ from human play; '
         'frequencies describe this population, not a significance test.',source_path=source['path'],
         checkpoint=source['checkpoint'],metadata_stream_sha256=stream.hexdigest(),
         script_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
         player_tier3_blind_hist=players,game_tier3_blind_hist=games,
         player_joint_total_blind_and_tier3_hist=joint,counts=checks,
         actual_human_game=dict(AI_main=26,AI_blinds=3,AI_tier3_blinds=3,
                                both_main=52,both_blinds=4,both_tier3_blinds=4))
(ART/'tier3_distribution.json').write_text(json.dumps(out,ensure_ascii=False,indent=2,sort_keys=True)+'\n')
print(json.dumps(checks),flush=True)
